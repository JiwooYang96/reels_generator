// Regenerates docs/SCENES.md from the scene registry, so the catalogue never drifts from the code.
// Usage: npx tsx scripts/catalog.ts
import fs from 'node:fs';
import {z} from 'zod';
import {SCENES} from '../src/scenes/registry';

const fieldLine = (name: string, s: any, required: boolean): string => {
  const t = s.type ?? (s.enum ? 'enum' : s.anyOf ? 'any' : '?');
  let type = t === 'array' ? `array of ${s.items?.type === 'object' ? 'objects' : s.items?.type}` : t;
  if (s.enum) type = s.enum.map((v: string) => `"${v}"`).join(' | ');
  const bits = [type];
  if (s.default !== undefined) bits.push(`default ${JSON.stringify(s.default)}`);
  if (s.minItems !== undefined || s.maxItems !== undefined) bits.push(`${s.minItems ?? 0}-${s.maxItems ?? 'n'} items`);
  if (s.maxLength !== undefined) bits.push(`max ${s.maxLength} chars`);
  let line = `- \`${name}\`${required ? '' : ' (optional)'}: ${bits.join(', ')}`;
  if (s.type === 'array' && s.items?.type === 'object') {
    const req = new Set<string>(s.items.required ?? []);
    line += `, each: ${Object.entries(s.items.properties).map(([k, v]: [string, any]) => `\`${k}\`${req.has(k) ? '' : '?'} ${v.enum ? v.enum.join('|') : v.type}`).join(', ')}`;
  }
  if (s.type === 'object' && s.properties) {
    const req = new Set<string>(s.required ?? []);
    line += ` {${Object.entries(s.properties).map(([k, v]: [string, any]) => `\`${k}\`${req.has(k) ? '' : '?'} ${v.type}`).join(', ')}}`;
  }
  return line;
};

const out: string[] = [
  '# Scene catalogue',
  '',
  'Generated by `npx tsx scripts/catalog.ts` from `src/scenes/registry.ts`. Do not edit by hand.',
  '',
  'Every plan scene has: `type`, `seconds` (1-8), `caption` (words; one or two `key: true`; `br: true` starts line 2), optional `theme` ("dark" | "light"), `source` (required for data scenes), and `props` as listed below. Scene 1 must be an `open.*` scene of 3 s or less.',
  '',
];

for (const [type, def] of Object.entries(SCENES)) {
  const js: any = z.toJSONSchema(def.schema as any, {io: 'input'});
  const req = new Set<string>(js.required ?? []);
  out.push(`## \`${type}\``, '', def.summary, '', `Default theme: ${def.defaultTheme}. Source line: ${def.needsSource ? 'required' : 'not needed'}.`, '');
  for (const [k, v] of Object.entries<any>(js.properties ?? {})) out.push(fieldLine(k, v, req.has(k)));
  out.push('');
}

fs.mkdirSync('docs', {recursive: true});
fs.writeFileSync('docs/SCENES.md', out.join('\n'));
console.log(`wrote docs/SCENES.md (${Object.keys(SCENES).length} scenes)`);
